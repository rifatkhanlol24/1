/**
 * Deterministically generates a unique bilingual Bangladeshi/international user from an integer index
 */
export function generateUniqueBilingualUser(index: number, targetFollowingId?: string): User {
  const safeIdx = Math.abs(index);
  const first = FIRST_NAMES[safeIdx % FIRST_NAMES.length];
  const last = LAST_NAMES[Math.floor(safeIdx / FIRST_NAMES.length) % LAST_NAMES.length];

  const fullNameBn = `${first.bn} ${last.bn}`;
  const fullNameEn = `${first.en} ${last.en}`;
  const fullName = `${fullNameBn} (${fullNameEn})`;

  const suffix = safeIdx > 0 ? `_${(safeIdx % 9999) + 1}` : '';
  const username = `${first.en.toLowerCase()}_${last.en.toLowerCase()}${suffix}`;
  const userId = `user-m-${safeIdx}`;

  const photoId = AVATAR_PHOTOS[safeIdx % AVATAR_PHOTOS.length];
  const bioBn = BIOS_BN[safeIdx % BIOS_BN.length];
  const bioEn = BIOS_EN[safeIdx % BIOS_EN.length];

  return {
    id: userId,
    email: `${first.en.toLowerCase()}.${last.en.toLowerCase()}${safeIdx}@1social.com`,
    username,
    fullName,
    fullNameBn,
    fullNameEn,
    avatar: `https://images.unsplash.com/photo-${photoId}?w=300&auto=format&fit=crop&q=80`,
    coverImage: 'https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?w=800&auto=format&fit=crop&q=80',
    bio: `${bioBn} • ${bioEn}`,
    bioBn,
    website: 'https://techlystb.blogspot.com',
    links: [{ id: `u-l-${safeIdx}-1`, title: 'Tech Lyst B', url: 'https://techlystb.blogspot.com' }],
    role: 'user',
    isVerified: safeIdx % 7 === 0,
    isVip: safeIdx % 19 === 0,
    isBanned: false,
    followers: [],
    following: targetFollowingId ? [targetFollowingId] : [],
    createdAt: new Date(Date.now() - (safeIdx * 86400000) % 31536000000).toISOString(),
  };
}

/**
 * Sanitizes any raw or robotic user object (e.g. USER-0001212008) into a realistic user
 */
export function sanitizeUserToBilingual(user: User): User {
  // If user already has a valid non-robotic fullName, preserve it completely
  if (
    user.fullName &&
    !user.fullName.startsWith('USER-') &&
    !user.username.startsWith('USER-')
  ) {
    return user;
  }

  let seed = 0;
  const numMatch = user.username.match(/\d+/) || user.fullName?.match(/\d+/) || user.id.match(/\d+/);
  if (numMatch) {
    seed = parseInt(numMatch[0].slice(-6), 10) || 1;
  } else {
    for (let i = 0; i < user.username.length; i++) {
      seed = (seed << 5) - seed + user.username.charCodeAt(i);
      seed |= 0;
    }
    seed = Math.abs(seed);
  }

  const generated = generateUniqueBilingualUser(seed);

  return {
    ...user,
    fullName: generated.fullNameEn,
    fullNameBn: generated.fullNameBn,
    fullNameEn: generated.fullNameEn,
    username: user.username || generated.username,
    avatar: user.avatar && !user.avatar.includes('1534528741775-53994a69daeb') ? user.avatar : generated.avatar,
    bio: user.bio || generated.bio,
  };
}
